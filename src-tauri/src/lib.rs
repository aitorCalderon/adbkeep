/// Writes `src/lib/bindings.ts`; run by `cargo test -p adbkeep export_bindings` and on debug startup.
#[cfg(any(debug_assertions, test))]
fn export_bindings(builder: &Builder<tauri::Wry>) {
    builder
        .export(
            specta_typescript::Typescript::default()
                .bigint(specta_typescript::BigIntExportBehavior::Number)
                .header("// @ts-nocheck\n// Generated by tauri-specta from src-tauri; do not edit.\n"),
            concat!(env!("CARGO_MANIFEST_DIR"), "/../src/lib/bindings.ts"),
        )
        .expect("export TypeScript bindings");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = specta_builder();
    #[cfg(debug_assertions)]
    export_bindings(&builder);

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_os::init())
        .plugin(tauri_plugin_store::Builder::default().build())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let log = Arc::new(CommandLog::new());
            let handle = app.handle().clone();
            log.set_listener(move |entry| {
                let _ = LogEvent(entry.clone()).emit(&handle);
            });
            let handle = app.handle().clone();
            let devices = DeviceManager::new(move |snapshot| {
                let _ = DeviceEvent(snapshot).emit(&handle);
            });
            let bundled = app.path().resource_dir().ok().map(|d| d.join("platform-tools"));
            app.manage(AppState::new(log, devices, bundled));
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

